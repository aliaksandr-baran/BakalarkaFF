eq_list = struct('name',{'Насос P-1','Насос P-2','Насос P-3','Насос P-4', ...
    'Насос P-5','Насос P-6','Экстрактор','Подогрев H-1','Подогрев H-2', ...
    'Конденс K-1','Конденс K-2','Конденс K-3','Испарит D-1','Испарит D-2'}, ...
    'type',{'pump','pump','pump','pump','pump','pump','column', ...
    'HEX','HEX','HEX','HEX','HEX','HEX','HEX'}, ...
    'cost_base',{3000,2100,2170,9720,2737,1771,43243,2124,2479, ...
    9912,23270,70855,169999,119029}, ...
    'CEPCI_base',{567.5,567.5,567.5,567.5,567.5,567.5,567.5, ...

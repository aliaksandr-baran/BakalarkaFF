    101325, 73500 + 740*9.81*1, merge(pump_opts,struct('dz',1)));
p4 = pump_sizing(struct('n',n6,'x',x6,'T',T_ext,'name','P-4 (экстракт)'), ...
    101325, 101325 + 1100*9.81*5, merge(pump_opts,struct('dz',5)));

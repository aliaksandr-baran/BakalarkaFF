%% ============================================================
%% ГЛАВНЫЙ СКРИПТ (ВАРИАНТ: ЧИСТАЯ ИЖ)
%% Разделение MTBE–Метанол / [BMIM][HSO4]
%%
%% Отличие от main_simulation.m (вариант «Регенерированная ИЖ»):
%%   растворитель S — СВЕЖАЯ (чистая) ионная жидкость: x_S = [0, 0, 1].
%%   Технологическая схема и все модели идентичны; меняется только
%%   состав растворителя на входе в экстрактор.
%%
%% В отличие от регенерированного варианта здесь НЕ используются
%% жёстко заданные «верифицированные» значения потоков из Excel
%% (они относятся к рег. ИЖ). Все потоки берутся из расчётных функций:
%%   * экстрактор   -> ext.extract / ext.raffinate
%%   * клапан V-1   -> V1.vapor / V1.liquid
%%   * испарители   -> D1/D2 .vapor / .liquid
%% ============================================================

clc; clear; close all;

addpath(fullfile(fileparts(mfilename('fullpath')), 'functions'));

fprintf('=========================================================\n');
fprintf(' МОДЕЛИРОВАНИЕ: Разделение MTBE-MeOH с [BMIM][HSO4]\n');
fprintf(' Вариант растворителя: ЧИСТАЯ (свежая) ИЖ\n');
fprintf('=========================================================\n\n');

%% ============================================================
%% РАЗДЕЛ 1: ПАРАМЕТРЫ СИСТЕМЫ
%% ============================================================

R = 8.314;       % [Дж/моль/К]
T_ext = 318.15;  % Температура экстрактора [К] = 45°C

alpha = 0.4;
delta_g = [ 0.0000,  5.5737, 19.2694;
            7.4991,  0.0000, 10.6456;
           16.2120,  0.5632,  0.0000];   % [кДж/моль]

ant = [20.84054, -2624.525, -46.15171;   % A = MTBE
       23.5347,  -3661.468, -32.77001];  % B = MeOH

MA = 88.15; MB = 32.04; MC = 236.29;

cpA_kgK    = 2.127;
cpB_coeff  = [0.8382, -0.003231, 8.296e-6, -1.689e-10];
cpIL_coeff = [753.28, -3.4195, 0.0063];

vap_A.A=46.23; vap_A.beta=0.2893; vap_A.Tc=497.1;
vap_B.A=45.3;  vap_B.alpha=-0.31; vap_B.beta=0.4241; vap_B.Tc=512.6;

thermo_opts = struct('cpA_kgK',cpA_kgK,'cpB_coeff',cpB_coeff,...
    'cpIL_coeff',cpIL_coeff,'vap_A',vap_A,'vap_B',vap_B,...
    'MA',MA,'MB',MB,'MC',MC);

% --- Условия процесса (вариант «Чистая ИЖ») ---
n_F = 531.1327;  x_F = [0.54, 0.46, 0.00];     % Питание, поток 1
n_S = 258.3784;  x_S = [0.00, 0.00, 1.00];      % СВЕЖАЯ чистая ИЖ, поток 5

hrs_year = 7920;   % часов/год

%% ============================================================
%% РАЗДЕЛ 2: ЭКСТРАКЦИОННАЯ КОЛОННА (5 ступеней, ЖЖЭ)
%% ============================================================

fprintf('=== 2. Экстрактор (5 ступеней, ЖЖЭ) ===\n');

feed_ext    = struct('n',n_F,'x',x_F,'T',T_ext,'name','Питание F');
solvent_ext = struct('n',n_S,'x',x_S,'T',T_ext,'name','Растворитель S (чистая ИЖ)');

ext_opts = struct(...
    'tol',     1e-8, ...
    'max_iter',3000, ...
    'damp',    0.15, ...
    'E_stage', 0.85, ...
    'HETS',    0.15, ...
    'rho_R',   740, ...
    'rho_E',   1230, ...
    'sigma',   15);

ext = extractor_column(feed_ext, solvent_ext, 5, delta_g, alpha, R, T_ext, ext_opts);

% Результаты экстрактора берём из РАСЧЁТА (не из Excel рег. ИЖ)
n6  = ext.extract.n;   x6  = ext.extract.x;     % Экстракт (поток 6)
n18 = ext.raffinate.n; x18 = ext.raffinate.x;   % Рафинат (поток 18)

fprintf('  Экстракт (пот.6):  n=%.3f кмоль/ч  x=[%.5f %.5f %.5f]\n', n6, x6);
fprintf('  Рафинат  (пот.18): n=%.3f кмоль/ч  x=[%.5f %.5f %.5f]\n', n18, x18);

%% ============================================================
%% РАЗДЕЛ 3: АНАЛИЗ МАССОПЕРЕНОСА В ЭКСТРАКТОРЕ
%% ============================================================

fprintf('\n=== 3. Анализ массопереноса ===\n');

mt = mass_transfer_analysis(ext.stage_xR, ext.stage_xE, ...
    ext.stage_nR, ext.stage_nE, delta_g, alpha, R, T_ext, ...
    struct('HETS',0.15));

%% ============================================================
%% РАЗДЕЛ 4: КЛАПАН V-1 (101.3 → 50 кПа)
%% ============================================================

fprintf('\n=== 4. Клапан V-1 и сепаратор фаз ===\n');

feed_V1 = struct('n',n6,'x',x6,'T',68+273.15,'P',101325,'name','V-1');
V1 = throttle_valve(feed_V1, 50e3, ant, delta_g, alpha, R, thermo_opts);

% Берём расчётный сплит фаз клапана
if V1.vapor.n > 0
    n9 = V1.vapor.n;   x9  = V1.vapor.x;
else
    n9 = n6*0.2;       x9  = [0.18, 0.82, 0.0];
end
x9(3) = 0;  if sum(x9) > 0, x9 = x9/sum(x9); end   % ИЖ нелетуча
n12 = max(V1.liquid.n, n6 - n9);  x12 = V1.liquid.x;

%% ============================================================
%% РАЗДЕЛ 5: ЖПЭ-РАСЧЁТ ПАРА (поток 9 → конденсатор K-1)
%% ============================================================

fprintf('\n=== 5. ЖПЭ-расчёт паров с сепаратора (поток 9) ===\n');

flash_opts = struct('tol',1e-9,'max_iter',500);
[V9, y9, x9_liq, T9_bub, conv9] = vle_flash(x9, 50e3, 45.114+273.15, ...
    ant, delta_g, alpha, R, flash_opts);

fprintf('  Поток 9 (пар, 50 кПа):  V_frac=%.4f  T_пузырьк=%.2f°C  сошлось=%d\n', ...
    V9, T9_bub-273.15, conv9);
fprintf('  Состав пара: yA=%.5f  yB=%.5f\n', y9(1), y9(2));

n11 = n9; x11 = x9;   % Рецикл (поток 11 = конденсат K-1)

%% ============================================================
%% РАЗДЕЛ 6: ИСПАРИТЕЛЬ D-1 (P = 2.45 кПа, MeOH продукт + рег. ИЖ)
%% ============================================================

fprintf('\n=== 6. Испаритель D-1 (P=2.45 кПа) ===\n');

feed_D1 = struct('n',n12,'x',x12,'T',45.114+273.15,'name','D-1');
D1_opts = thermo_opts;
D1_opts.T_steam = 145+273.15;
D1_opts.U_evap  = 600;

D1 = evaporator_calc(feed_D1, 2.45e3, ant, delta_g, alpha, R, D1_opts);

n13 = D1.vapor.n;  x13 = D1.vapor.x;   % Дистиллят (пар MeOH)
n16 = D1.liquid.n; x16 = D1.liquid.x;  % Остаток (регенерированная ИЖ)

%% ============================================================
%% РАЗДЕЛ 7: ИСПАРИТЕЛЬ D-2 (P = 73.5 кПа, MTBE продукт)
%% ============================================================

fprintf('\n=== 7. Испаритель D-2 (P=73.5 кПа) ===\n');

feed_D2 = struct('n',n18,'x',x18,'T',45+273.15,'name','D-2');
D2_opts = thermo_opts;
D2_opts.T_steam = 145+273.15;
D2_opts.U_evap  = 900;

D2 = evaporator_calc(feed_D2, 73.5e3, ant, delta_g, alpha, R, D2_opts);

n20 = D2.vapor.n;  x20 = D2.vapor.x;   % Дистиллят (MTBE)
n23w = D2.liquid.n; x23w = D2.liquid.x; % Остаток

%% ============================================================
%% РАЗДЕЛ 8: ТЕПЛООБМЕННИКИ (расчёт поверхности)
%% ============================================================

fprintf('\n=== 8. Теплообменники (LMTD-метод) ===\n');

hx_H1 = heat_exchanger( ...
    struct('T_in',145,'T_out',145,'name','Пар 4 бар'), ...
    struct('T_in',25, 'T_out',45, 'name','Пит. поток'), ...
    437.02, struct('type','shell_tube','U',750));
hx_H2 = heat_exchanger( ...
    struct('T_in',145,'T_out',145,'name','Пар 4 бар'), ...
    struct('T_in',45, 'T_out',68, 'name','Экстракт'), ...
    715.87, struct('type','shell_tube','U',890));
hx_K1 = heat_exchanger( ...
    struct('T_in',45.114,'T_out',37.646,'name','Пар пот.9'), ...
    struct('T_in',20,    'T_out',35,    'name','Охл. вода'), ...
    1159.62, struct('type','shell_tube','U',1500));
hx_K2 = heat_exchanger( ...
    struct('T_in',45.124,'T_out',25,'name','Пар D-1'), ...
    struct('T_in',5,     'T_out',20,'name','Охл. вода'), ...
    2584.12, struct('type','shell_tube','U',2250));
hx_K3 = heat_exchanger( ...
    struct('T_in',45.044,'T_out',25,'name','Пар D-2'), ...
    struct('T_in',5,     'T_out',20,'name','Охл. вода'), ...
    2576.54, struct('type','shell_tube','U',750));
hx_D1 = heat_exchanger( ...
    struct('T_in',145,'T_out',145,'name','Пар 4 бар'), ...
    struct('T_in',20, 'T_out',45.124,'name','Пот. 12'), ...
    2469.61, struct('type','shell_tube','U',450));
hx_D2 = heat_exchanger( ...
    struct('T_in',145,'T_out',145,'name','Пар 4 бар'), ...
    struct('T_in',20, 'T_out',45.0,'name','Рафинат 18'), ...
    2276.68, struct('type','shell_tube','U',900));

%% ============================================================
%% РАЗДЕЛ 9: НАСОСЫ
%% ============================================================

fprintf('\n=== 9. Расчёт насосов ===\n');

pump_opts = thermo_opts;

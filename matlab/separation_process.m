%% ============================================================
%% РАЗДЕЛ 6: СЕПАРАТОР ФАЗ (SF) И РЕЦИКЛ
%% ============================================================
% Пар (поток 9) конденсируется в K-1 → поток 10/11 рециркулируется
% обратно в смеситель M-1 и смешивается с сырьевым потоком 1

n10 = n9;  x10 = x9;  % после конденсатора K-1 (жидкость)
n11 = n10; x11 = x10; % рецикл в M-1


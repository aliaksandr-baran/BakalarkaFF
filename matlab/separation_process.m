% Поток 2,3 (питание после смешения с рециклом, поток на входе в экстрактор)
n23  = 647.976;
x23  = [0.47601, 0.52378, 0.00021];

% Поток 5 (регенерированная ИЖ на вход экстрактора)
n5   = n_S;   x5 = x_S;

% Поток 18 (финальный рафинат с выхода экстрактора)
n18  = 287.206;
x18  = [0.99679, 0.00047, 0.00275];

% Поток 6  (финальный экстракт с выхода экстрактора)
n6   = 619.130;

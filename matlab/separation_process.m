% Изоэнтальпийное расширение потока 7 (нагретый экстракт, 68°C)
% Условия за клапаном: T_V1, P = 50 кПа  → двухфазная смесь (поток 8)
% Парная фаза (поток 9): MTBE + MeOH (без ИЖ)
% Жидкая фаза (поток 12): обогащённая ИЖ

% Данные из Excel (поток 7 → поток 8 → разделение на 9 и 12)
T_V1_out = 45.114 + 273.15;   % K  (температура после клапана)
n7  = n6;     x7  = x6;       % поток 7 = нагретый поток 6
P_V1 = 50e3;  % [Па]

% Расчёт давлений насыщения при T_V1_out
PA_sat = Psat(ant_A, T_V1_out);

%% ============================================================
%% РАЗДЕЛ 1: ПАРАМЕТРЫ СИСТЕМЫ
%% ============================================================

% --- Компоненты ---
% A = MTBE         (метил-трет-бутиловый эфир, C5H12O)
% B = Метанол      (CH3OH)
% C = [BMIM][HSO4] (1-бутил-3-метилимидазолий гидросульфат, ионная жидкость)

% Молярные массы [кг/кмоль]
M_A = 88.15;
M_B = 32.04;
M_C = 236.29;
M = [M_A, M_B, M_C];

% Универсальная газовая постоянная [Дж/моль/К]
R = 8.314;

% Рабочая температура экстрактора [K]
T_ext = 318.15;  % 45 °C

% --- Параметры модели NRTL для системы MTBE(1)–MeOH(2)–[BMIM][HSO4](3)
%     при 318,15 K. Источник: J. Chem. Thermodynamics 132 (2019) 76-82.
%     delta_g [кДж/моль]: delta_g(i,j) — энергия взаимодействия пары i-j
alpha = 0.4;   % параметр нерандомности (одинаков для всех пар)

% Матрица дельта_g [кДж/моль]; delta_g(i,i) = 0 (диагональ)
% Строки/столбцы: [A(1), B(2), C(3)]
delta_g = [ 0.0000,  5.5737, 19.2694;
            7.4991,  0.0000, 10.6456;
           16.2120,  0.5632,  0.0000];

% --- Параметры уравнения Антуана (форма ln P[Па] = A + B/(T+C), T[K])
%     Источник: Excel-файл Parametre
%     Компонент A (MTBE):
ant_A = [20.84054, -2624.525, -46.15171];
%     Компонент B (Метанол):
ant_B = [23.5347,  -3661.468, -32.77001];
%     Компонент C ([BMIM][HSO4]): нелетуч — P_sat_C = 0 по определению

% --- Параметры теплоёмкости метанола (уравнение DIPPR, ккал/кг/К → кДж/кмоль/К)
%     cp_B(T) = (a + b*T + c*T^2 + d*T^3) * M_B * 4.184 [кДж/кмоль/К]  T[K]
cp_B_coeff = [0.8382, -0.003231, 8.296e-6, -1.689e-10]; % коэфф. в ккал/кг/К

% --- Параметры теплоёмкости MTBE — считается постоянной [кДж/кг/К]
cp_A_kgK = 2.127;   % при 20°C, источник: таблица 1 диссертации

% --- Параметры теплоёмкости ИЖ [EMIM][HSO4] (аппроксимация 2-й степени, кДж/кмоль/К)
%     cp_C(T) = a + b*(T-273.15) + c*(T-273.15)^2     T[K]
cp_IL_coeff = [753.28, -3.4195, 0.0063]; % для [EMIM][HSO4] как прокси

% --- Параметры расчёта теплоты испарения (уравнение Ватсона-Масса)
%     ΔvapH(T) = A * ((Tc - T)/(Tc - Tref))^(alpha + beta*(T/Tc))
%     Метанол:
vap_B.A  = 45.3;    vap_B.alpha = -0.31; vap_B.beta = 0.4241;
vap_B.Tc = 512.6;   % [K]
%     MTBE:
vap_A.A  = 46.23;   vap_A.beta  = 0.2893;
vap_A.Tc = 497.1;   % [K]

% Коэффициент масштабирования (из Excel: единица производительности ×21.25)
scale = 21.2453078;

% --- Условия процесса (из материального баланса Excel, вариант «Регенерированная ИЖ»)
% Питание экстрактора: поток 1
n_F  = 531.1327;          % кмоль/ч
x_F  = [0.54, 0.46, 0.00]; % мольные доли A, B, C

% Растворитель (регенерированная ИЖ): поток 5
n_S  = 258.3784;
x_S  = [0.001559, 0.019959, 0.978483];

% Рабочий год
hrs_year = 7920;   % часов/год (330 дней)

fprintf('\n');
fprintf('=========================================================\n');
fprintf('МОДЕЛИРОВАНИЕ: Разделение MTBE-MeOH с [BMIM][HSO4]\n');
fprintf('=========================================================\n');
fprintf('Питание (поток 1):  %.2f кмоль/ч   xA=%.3f  xB=%.3f  xC=%.3f\n', ...
    n_F, x_F(1), x_F(2), x_F(3));
fprintf('Растворитель (пот.5): %.2f кмоль/ч  xA=%.4f xB=%.4f  xC=%.4f\n', ...
    n_S, x_S(1), x_S(2), x_S(3));
fprintf('---------------------------------------------------------\n\n');

%% ============================================================
%% РАЗДЕЛ 2: ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
%% ============================================================

% --- NRTL-коэффициент активности (вложенная функция в конце файла)
% --- Давление насыщенного пара по уравнению Антуана [Па]
Psat = @(ant, T) exp(ant(1) + ant(2)/(T + ant(3)));

% --- Теплоёмкость метанола [кДж/кмоль/К], T [K]
cp_methanol = @(T) (cp_B_coeff(1) + cp_B_coeff(2)*T + cp_B_coeff(3)*T^2 ...
    + cp_B_coeff(4)*T^3) * M_B * 4.184;

% --- Теплоёмкость MTBE [кДж/кмоль/К]
cp_MTBE = @(T) cp_A_kgK * M_A;   % постоянная, T-зависимость игнорируется

% --- Теплоёмкость ИЖ [кДж/кмоль/К], t = T-273.15
cp_IL = @(T) cp_IL_coeff(1) + cp_IL_coeff(2)*(T-273.15) ...
    + cp_IL_coeff(3)*(T-273.15)^2;

% --- Интегральная теплоёмкость смеси [кДж/кмоль] от T1 до T2
%     cp_mix(x, T) = sum(x_i * cp_i(T))
cp_stream_integral = @(x, T1, T2) ...
    integral(@(T) x(1)*cp_MTBE(T) + x(2)*cp_methanol(T) + x(3)*cp_IL(T), ...
    T1, T2);

% --- Теплота испарения метанола [кДж/моль], T [K]
Hvap_B = @(T) vap_B.A * ((vap_B.Tc - T)/(vap_B.Tc - 298.15))^...
    (vap_B.alpha + vap_B.beta * (T/vap_B.Tc));

% --- Теплота испарения MTBE [кДж/моль], T [K]
Hvap_A = @(T) vap_A.A * ((vap_A.Tc - T)/(vap_A.Tc - 298.15))^...
    vap_A.beta;

%% ============================================================
%% РАЗДЕЛ 3: СИМУЛЯЦИЯ 5-СТУПЕНЧАТОГО ЭКСТРАКТОРА (ЖЖЭ)
%% ============================================================
% Метод: последовательная подстановка (successive substitution)
% с матричным решением материального баланса (уравнения 23-31 диссертации)

fprintf('--- 2. Симуляция экстракционной колонны (5 ступеней) ---\n\n');

N = 5;   % число теоретических контактов

% Начальные значения потоков [кмоль/ч] — первое приближение
nR = zeros(1, N+1);  % потоки рафинатов  (nR(1)=F, nR(6)=R5)
nE = zeros(1, N+1);  % потоки экстрактов (nE(1)=E1, nE(6)=S)

% Матрицы мольных долей: строка = ступень, столбец = компонент [A B C]
xR = zeros(N+1, 3);
xE = zeros(N+1, 3);

% Граничные условия
nR(1)   = n_F;    xR(1,:)   = x_F;    % питание
nE(N+1) = n_S;    xE(N+1,:) = x_S;    % растворитель

% Начальное приближение равновесных долей (из Excel-результата)
xR_init = [x_F; 0.863, 0.135, 0.001; 0.976, 0.023, 0.001;
           0.994, 0.005, 0.001; 0.998, 0.001, 0.001; 0.999, 0.0002, 0.0005];
xE_init = [0.036, 0.556, 0.408; 0.036, 0.556, 0.408; 0.013, 0.190, 0.797;
           0.003, 0.042, 0.955; 0.002, 0.008, 0.990; x_S];
xR = xR_init;
xE = xE_init;
nR(N+1) = n_F * (x_F(2) - xR_init(N+1,2)) / ...
    (xE_init(1,2) - xR_init(N+1,2)) * 0.5 + n_S;

% --- Итерационный цикл экстрактора ---
tol_ext = 1e-8;
max_iter_ext = 2000;
err_ext = 1; iter_ext = 0;

while err_ext > tol_ext && iter_ext < max_iter_ext
    iter_ext = iter_ext + 1;
    xR_old = xR; xE_old = xE;

    % Вычисление коэффициентов активности для каждой ступени
    for n = 1:N
        gR = nrtl_gamma(xR(n+1,:), delta_g, alpha, R, T_ext);
        gE = nrtl_gamma(xE(n,:), delta_g, alpha, R, T_ext);
        K  = gR ./ gE;  % коэфф. распределения K_i = gamma_R_i / gamma_E_i

        % Для каждого компонента — матричная система (ур. 23-31 диссертации)
        % Решаем: A * xR_vec = b_vec для каждого компонента отдельно
        for ci = 1:3
            % Строим матрицу коэффициентов 5×5 для вектора xR(1..5) компонента ci
            A_mat = zeros(N, N);
            b_vec = zeros(N, 1);
            for row = 1:N
                % Пересчёт K в каждой ступени
                gR_n = nrtl_gamma(xR(row+1,:), delta_g, alpha, R, T_ext);
                gE_n = nrtl_gamma(xE(row,:), delta_g, alpha, R, T_ext);
                K_n  = gR_n ./ gE_n;
                Kci  = K_n(ci);

                % Потоки для текущей ступени
                nRn  = nR(row); nEn  = nE(row+1);
                nRn1 = nR(row+1); nEn1 = nE(row);
                coef = nRn + Kci * nEn;
                if row == 1
                    A_mat(row, row)   =  coef;
                    if row < N
                        A_mat(row, row+1) = -Kci * nE(row+1);
                    end
                    b_vec(row) = nR(1)*x_F(ci) + Kci*nE(N+1)*x_S(ci);
                elseif row == N
                    A_mat(row, row)   =  coef;
                    A_mat(row, row-1) = -nR(row);
                    b_vec(row) = Kci * nE(N+1) * x_S(ci);
                else
                    A_mat(row, row)   =  coef;
                    A_mat(row, row-1) = -nR(row);
                    if row < N
                        A_mat(row, row+1) = -Kci * nE(row+1);
                    end
                    b_vec(row) = 0;
                end
            end
            % Решение системы
            xR_sol = A_mat \ b_vec;
            for row = 1:N
                xR(row+1, ci) = max(0, xR_sol(row));
            end
        end

        % Нормализация мольных долей рафинатов
        for n2 = 2:N+1
            s = sum(xR(n2,:));
            if s > 0, xR(n2,:) = xR(n2,:)/s; end
        end

        % Равновесные доли экстрактов через NRTL
        for n2 = 1:N
            gR_n = nrtl_gamma(xR(n2+1,:), delta_g, alpha, R, T_ext);
            gE_n = nrtl_gamma(xE(n2,:), delta_g, alpha, R, T_ext);
            K_n  = gR_n ./ gE_n;
            xE_new = K_n .* xR(n2+1,:);
            s = sum(xE_new);
            if s > 0, xE(n2,:) = xE_new/s; end
        end
    end

    err_ext = sum(abs(xR(:) - xR_old(:))) + sum(abs(xE(:) - xE_old(:)));
end

% --- Пересчёт потоков ---
% Полный материальный баланс по компоненту B (метанол)
% n_E1*xE1_B + n_R5*xR5_B = n_F*xF_B + n_S*xS_B
xR5 = xR(N+1,:);
xE1 = xE(1,:);
% Решаем 2 уравнения: n_E1 + n_R5 = n_F + n_S  и  n_E1*xE1_A + n_R5*xR5_A = n_F*xF_A + n_S*xS_A
mat2 = [1, 1; xE1(1), xR5(1)];
rhs2 = [n_F + n_S; n_F*x_F(1) + n_S*x_S(1)];
sol2 = mat2 \ rhs2;
n_E1 = sol2(1);
n_R5 = sol2(2);

% Потоки на каждой ступени из баланса
nE(1) = n_E1;
nR(N+1) = n_R5;
% Промежуточные потоки
for n = 1:N-1
    nR(n+1) = (n_F*x_F(1) + n_S*x_S(1) - nE(1)*xE(1,1)) / ...
        max(xR(n+1,1), 1e-12) * 0.5 + nR(1)*0.5; % приближение
end
% Уточняем балансом
for n = 1:N
    nE(n+1) = nE(1) + nR(1) - nR(n+1);
end
% Итоговые балансы
for n = 1:N
    nRn = nR(n); nEn1 = nE(n+1);
    nRn1 = (nRn * xR(n,1) + nEn1 * xE(n+1,1) - nE(n)*xE(n,1)) / max(xR(n+1,1),1e-9);
    nR(n+1) = max(nRn1, 0);
    nE(n)   = nR(n) + nEn1 - nR(n+1);
end
% Финальные значения из материального баланса
n_E1_final = n_F + n_S - n_R5;

fprintf('Итерации экстрактора: %d  |  ошибка: %.2e\n\n', iter_ext, err_ext);


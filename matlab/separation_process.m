function gamma = nrtl_gamma(x, delta_g, alpha, R, T)
%NRTL_GAMMA  Коэффициенты активности по модели NRTL для n-компонентной смеси
%   x       — вектор мольных долей [1×n]
%   delta_g — матрица энергий взаимодействия [кДж/моль], n×n
%   alpha   — параметр нерандомности (скаляр или матрица)
%   R       — газовая постоянная [Дж/моль/К]
%   T       — температура [К]
%   Возвращает: gamma — вектор коэффициентов активности [1×n]

    n = length(x);
    x = max(x, 1e-14);
    x = x / sum(x);

    % Параметры tau и G (уравнения 15-17 диссертации)
    tau = (delta_g * 1000) ./ (R * T);   % безразмерные
    G   = exp(-alpha .* tau);             % матрица G_ij

    % Суммы S_j = sum_k(x_k * G_kj)
    S = x * G;   % вектор [1×n]

    % Первое слагаемое lngamma_i (уравнение 14, первая сумма)
    xG  = x .* G;    % матрица x_k * G_kj  (строка)
    xtG = x .* (tau .* G);  % матрица x_k * tau_kj * G_kj

    ln_gamma = zeros(1, n);
    for i = 1:n
        % sum_j [xj*Gij/Sj * (tau_ij - sum_k(xk*tau_kj*Gkj)/Sj)]
        term1 = sum(xtG(:,i)') / S(i);   % числитель первой суммы по j=i
        term2 = 0;
        for j = 1:n
            term2 = term2 + (xG(j) * G(i,j) / S(j)) * ...
                (tau(i,j) - sum(xtG(:,j)') / S(j));
        end
        ln_gamma(i) = term1 + term2;
    end
    gamma = exp(ln_gamma);
end


function [xE, xR, success] = lle_solver(z_feed, delta_g, alpha, R, T)
%LLE_SOLVER  Расчёт ЖЖЭ (жидкость-жидкость) методом последовательной замены
%   z_feed — общий состав системы [1×3]
%   Возвращает равновесные составы xE (экстракт) и xR (рафинат)
%   Метод: successive substitution с демпфированием 0.2/0.8

    tol = 1e-9;  max_iter = 2000;
    success = false;

    % Начальные приближения — фазы далеко друг от друга
    xR = [0.97, 0.02, 0.01];
    xE = [0.01, 0.02, 0.97];

    diff_val = 1;  iter = 0;

    while diff_val > tol && iter < max_iter
        iter = iter + 1;
        gR = nrtl_gamma(xR, delta_g, alpha, R, T);
        gE = nrtl_gamma(xE, delta_g, alpha, R, T);

        K = gR ./ gE;
        xE_old = xE;

        % Метод последовательной замены с демпфированием
        xE_new = xE ./ sum(K .* xE);
        xE = 0.2 * xE_new + 0.8 * xE_old;

        xR = K .* xE;
        xR = xR / sum(xR);

        diff_val = sum(abs(xE - xE_old));
    end

    % Проверка нетривиальности решения (фазы должны отличаться)
    if sum(abs(xR - xE)) > 5e-3
        success = true;
    end
end

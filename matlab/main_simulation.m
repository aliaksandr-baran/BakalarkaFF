%% ============================================================
%% Вспомогательная функция объединения структур
%% ============================================================
function s = merge(s1, s2)
    s = s1;
    flds = fieldnames(s2);
    for k = 1:length(flds)
        s.(flds{k}) = s2.(flds{k});
    end
end
